"""Stage 7: reporting.

Two views of the SAME underlying review (this is the manipulation in Claim 1):
  report.md / report_only text      : the final report (PRISMA counts, tables, synthesis)
  report_evidence.html / evidence text : report + supporting passages, quote checks, criterion-level
                                         eligibility decisions, term IDs, flags, revision history,
                                         and a feedback box that produces a CLI command.
"""
from __future__ import annotations

