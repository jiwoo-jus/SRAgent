from ..context import Ctx


def prisma(ctx: Ctx) -> dict:
    st = ctx.store
    s = (st.get("search") or {}).get("data", {})
    screens = st.by_type("screen")
    ta_excl = [n for n in screens if n["data"]["stage"] == "title_abstract" and n["data"]["decision"] == "exclude"]
    ft = [n for n in screens if n["data"]["stage"] == "full_text"]
    ft_excl = [n for n in ft if n["data"]["decision"] == "exclude"]
    reasons = {}
    for n in ft_excl:
        for c in n["data"].get("because", []) or ["unspecified"]:
            reasons[c] = reasons.get(c, 0) + 1
    return {"identified": s.get("n_identified"), "duplicates": s.get("n_duplicates"),
            "screened": len(screens), "excluded_title_abstract": len(ta_excl),
            "fulltext_assessed": len(ft), "excluded_fulltext": len(ft_excl),
            "excluded_fulltext_reasons": reasons,
            "awaiting_classification": sum(1 for n in screens if n["data"]["decision"] == "awaiting"),
            "included": len(st.included_ids())}


def review_title(p: dict) -> str:
    import re
    t = p.get("title") or "Systematic review"
    return re.sub(r"\s*[:\-]\s*(a\s+)?systematic review protocol\s*$", ": a systematic review", t, flags=re.I)


def _crit_lookup(ctx):
    p = (ctx.store.get("protocol") or {}).get("data", {})
    return {c["id"]: c["text"] for c in p.get("criteria", [])}


def report_markdown(ctx: Ctx) -> str:
    st = ctx.store
    p = st.get("protocol")["data"]
    pr = prisma(ctx)
    crit = _crit_lookup(ctx)
    fields = [f["name"] for f in ctx.topic["extraction_fields"]]
    L = [f"# {review_title(p)}", "",
         f"**Review question.** {p.get('question')}", "",
         "*Research prototype output. Generated by an AI agent; requires human verification before any use.*", "",
         "## Methods", "",
         "**Eligibility criteria**", ""]
    L += [f"- {c['id']} ({c['type']}, {c.get('stage', 'title_abstract')}): {c['text']}" for c in p.get("criteria", [])]
    s = (st.get("search") or {}).get("data", {})
    L += ["", f"**Search.** PubMed: `{s.get('query', '')}` ({s.get('hits', '?')} hits).", "",
          "## Study selection (PRISMA)", "",
          f"Records identified: {pr['identified']}; duplicates removed: {pr['duplicates']}; "
          f"screened: {pr['screened']}; excluded at title/abstract: {pr['excluded_title_abstract']}; "
          f"full texts assessed: {pr['fulltext_assessed']}; excluded at full text: {pr['excluded_fulltext']}; "
          f"awaiting classification (human decision needed): {pr['awaiting_classification']}; "
          f"**included: {pr['included']}**.", ""]
    ft_ex = [n for n in st.by_type("screen") if n["data"]["stage"] == "full_text" and n["data"]["decision"] == "exclude"]
    if ft_ex:
        L += ["**Studies excluded at full text**", "", "| Study | Title | Reason |", "|---|---|---|"]
        for n in ft_ex:
            rid = n["id"].split(":", 1)[1]
            t = st.get(f"rec:{rid}")["data"].get("title", "")[:90]
            why = "; ".join(f"{c}: {crit.get(c, '')}" for c in n["data"].get("because", []))
            L.append(f"| {rid} | {t} | {why} |")
        L.append("")
    L += ["## Characteristics of included studies", "",
          "| Study | " + " | ".join(fields) + " |", "|" + "---|" * (len(fields) + 1)]
    for rid in st.included_ids():
        n = st.get(f"ext:{rid}")
        if not n or n["status"] != "active":
            continue
        vals = [n["data"]["fields"].get(f, {}).get("value", "NR").replace("|", "/").replace("\n", " ") for f in fields]
        L.append(f"| {rid} | " + " | ".join(vals) + " |")
    L += ["", "## Risk of bias (draft)", ""]
    doms = [d["name"] for d in ctx.topic["rob_domains"]]
    L += ["| Study | " + " | ".join(doms) + " | Overall |", "|" + "---|" * (len(doms) + 2)]
    for rid in st.included_ids():
        n = st.get(f"rob:{rid}")
        if not n or n["status"] != "active":
            continue
        jd = {d.get("domain"): d.get("judgment") for d in n["data"]["domains"]}
        L.append(f"| {rid} | " + " | ".join(str(jd.get(d, "?")) for d in doms) + f" | {n['data']['overall']} |")
    L += ["", "## Synthesis", ""]
    for n in st.by_type("synthesis", active_only=True):
        d = n["data"]
        L.append(f"- **[{d['id']}]** {d['text']} [{', '.join(d['cites'])}]")
    L += ["", "## References (included studies)", ""]
    for rid in st.included_ids():
        r = st.get(f"rec:{rid}")["data"]
        L.append(f"- [{rid}] {r.get('authors', '')}. {r.get('title', '')} {r.get('journal', '')} {r.get('year', '')}. "
                 f"{'PMID ' + r['pmid'] if r.get('pmid') else ''} {'doi:' + r['doi'] if r.get('doi') else ''}")
    return "\n".join(L) + "\n"


def evidence_text(ctx: Ctx, max_chars_per_study: int = 0) -> str:
    """Plain-text evidence-linked bundle (used by the simulated reviewer in Claim 1)."""
    st = ctx.store
    crit = _crit_lookup(ctx)
    L = ["## EVIDENCE-LINKED DETAILS", "", "### Eligibility decisions (criterion level)"]
    for n in st.by_type("screen"):
        rid = n["id"].split(":", 1)[1]
        d = n["data"]
        if d["stage"] == "title_abstract" and d["decision"] == "exclude" and not n["flags"]:
            # keep bundle compact: TA exclusions listed briefly
            L.append(f"[screen:{rid}] {d['decision']} at {d['stage']} because {d.get('because')}")
            continue
        L.append(f"[screen:{rid}] decision={d['decision']} stage={d['stage']} because={d.get('because')}")
        for a in d.get("criteria", []):
            L.append(f"    {a.get('id')} ({crit.get(a.get('id'), '')[:60]}): {a.get('assessment')} | evidence: {_ev_txt(a)}")
    L += ["", "### Extracted data with supporting passages"]
    for rid in st.included_ids():
        n = st.get(f"ext:{rid}")
        if not n:
            continue
        L.append(f"[ext:{rid}] (source: {n['data']['source_kind']})")
        for k, v in n["data"]["fields"].items():
            chk = v.get("check", {}).get("status", "-")
            tm = "; ".join(f"{t['term']}->{t['status']} {t['ids']}" for t in v.get("terms", []))
            L.append(f"    {k}: {v['value']} | evidence[{chk}]: {_ev_txt(v)}" + (f" | terms: {tm}" if tm else ""))
    L += ["", "### Risk-of-bias rationales"]
    for rid in st.included_ids():
        n = st.get(f"rob:{rid}")
        if not n:
            continue
        L.append(f"[rob:{rid}] overall={n['data']['overall']}")
        for d in n["data"]["domains"]:
            L.append(f"    {d.get('domain')}: {d.get('judgment')} | {d.get('rationale', '')} | evidence: {_ev_txt(d)}")
    L += ["", "### Synthesis statements: cited evidence and self-check"]
    for n in st.by_type("synthesis", active_only=True):
        v = n["data"].get("verification") or {}
        L.append(f"[{n['data']['id']}] cites={n['data']['cites']} scope={n['data'].get('scope', '')} "
                 f"self-check={v.get('support', 'n/a')}")
        L.append("    populations of cited studies: " + cited_populations(ctx, n["data"]["cites"]))
    flags = [(n["id"], f) for n in st.nodes.values() for f in n["flags"] if f["status"] == "open"]
    if flags:
        L += ["", "### Open flags"] + [f"[{nid}] {f['text']}" for nid, f in flags]
    return "\n".join(L)


def sources_text(ctx: Ctx, rids: list[str] | None = None, max_chars: int = 6000) -> str:
    st = ctx.store
    rids = rids if rids is not None else st.included_ids()
    out = ["## SOURCE PAPERS"]
    for rid in rids:
        t, kind = st.text_of(rid)
        out.append(f"\n### Source {rid} ({kind})\n{t[:max_chars]}")
    return "\n".join(out)


